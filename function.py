for q in questions[10:]:
    st.markdown(f"**{q['question']}**")
    user_answers[q["id"]] = st.radio(
        f"เลือกคำตอบสำหรับข้อ {q['id']}:", 
        q["options"], 
        index=None, 
        key=f"q_{q['id']}"
    )
    st.divider()

# -------------------------------------------------------------
# ปุ่มส่งข้อสอบและตรวจคะแนน
# -------------------------------------------------------------
if st.button("ส่งคำตอบ 🚀", type="primary"):
    score = 0
    st.header("📊 ผลการสอบ")
    
    for q in questions:
        user_ans = user_answers.get(q["id"])
        if user_ans == q["answer"]:
            score += 1

    st.subheader(f"คุณได้คะแนน: {score} / 20 คะแนน")
    
    if score >= 16:
        st.success("🎉 สุดยอดมาก! ระดับความรู้สาย Gifted แน่นมากๆ ครับ")
    elif score >= 10:
        st.info("👍 ทำได้ดีครับ! ลองทบทวนข้อที่ผิดเพิ่มเติมนะ")
    else:
        st.warning("💪 พยายามอีกนิด! ค่อยๆ สรุปแนวคิดทีละข้อครับ")

    st.markdown("---")
    st.subheader("💡 เฉลยอย่างรายละเอียด")
    for q in questions:
        user_ans = user_answers.get(q["id"])
        is_correct = user_ans == q["answer"]
        icon = "✅" if is_correct else "❌"
        
        with st.expander(f"ข้อที่ {q['id']}: ตอบ {q['answer']} {icon}"):
            st.write(f"**คำตอบของคุณ:** {user_ans if user_ans else 'ไม่ได้ตอบ'}")
            st.write(f"**เฉลย:** {q['answer']}")
            st.write(f"**คำอธิบาย:** {q['explanation']}")
